double TWOM_SQRTd(double a)
{
    return sqrt(a);
}

float TWOM_SQRTf(float a)
{
    return (float)sqrt(a);
}

int TWOM_SQRTi(int a)
{
    return TWOM_RoundToNearestIntd(sqrt(a));
}
