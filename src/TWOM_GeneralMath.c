double TWOM_RoundToNearestIntd(double a)
{
    if (a >= 0.0)
        return TWOM_Floord(a + 0.5);

    return TWOM_Ceild(a - 0.5);
}

float TWOM_RoundToNearestIntf(float a)
{
    if (a >= 0.0)
        return TWOM_Floorf(a + 0.5);

    return TWOM_Ceilf(a - 0.5);
}

